"""
Генератор учебной базы b2c.db: клиенты банка, операции по картам, показы предложений.

Данные НЕ настоящие: все числа придуманы генератором случайных чисел,
но с правдоподобными закономерностями, чтобы было что находить в SQL:
  - премиум-клиенты старше, тратят больше и чаще;
  - летом много трат на путешествия, в сентябре растёт одежда;
  - 45 клиентов вообще без операций;
  - предложения чаще кликают, если они про то, на что клиент и так тратит.

Запуск: python generate_db.py  -> рядом появится b2c.db
Нужны библиотеки: pip install numpy pandas
"""
import sqlite3
from pathlib import Path

import numpy as np
import pandas as pd

# Генератор случайных чисел с фиксированным «зерном» (seed).
# С одним и тем же seed каждый запуск даёт ровно те же данные.
# Поменяешь 2026 на другое число — получишь другую базу.
rng = np.random.default_rng(2026)

# ===================================================================
# 1. КЛИЕНТЫ
# ===================================================================
N = 2000  # сколько клиентов

# Сегмент: 70% массовых, 22% массовых высокодоходных, 8% премиум
seg = rng.choice(["Массовый", "Массовый высокодоходный", "Премиум"], N, p=[0.70, 0.22, 0.08])

# Возраст зависит от сегмента: средний возраст премиум ~44, МВД ~38, массовых ~33.
# rng.normal(среднее, разброс, сколько) — нормальное распределение.
# np.clip обрезает значения в диапазон 18–75 лет.
age = np.clip(
    np.where(seg == "Премиум", rng.normal(44, 10, N),
    np.where(seg == "Массовый высокодоходный", rng.normal(38, 10, N),
             rng.normal(33, 12, N))),
    18, 75,
).astype(int)

# Город с заданными долями: треть клиентов из Москвы и т.д.
city = rng.choice(
    ["Москва", "Санкт-Петербург", "Екатеринбург", "Новосибирск", "Казань", "Нижний Новгород", "Краснодар"],
    N, p=[0.34, 0.16, 0.11, 0.10, 0.10, 0.10, 0.09],
)

# Вероятность подписки СберПрайм: у премиум 75%, у МВД 45%, у массовых 18%
prime_p = np.select([seg == "Премиум", seg == "Массовый высокодоходный"], [0.75, 0.45], 0.18)

clients = pd.DataFrame({
    "client_id": np.arange(100001, 100001 + N),               # 100001, 100002, ...
    "gender": rng.choice(["М", "Ж"], N),                       # пол 50/50
    "age": age,
    "city": city,
    "segment": seg,
    "has_sberprime": (rng.random(N) < prime_p).astype(int),    # 1 = есть подписка
    # дата регистрации: случайный день в промежутке 2015-01-01 + 0…4100 дней
    "reg_date": (pd.Timestamp("2015-01-01")
                 + pd.to_timedelta(rng.integers(0, 4100, N), unit="D")).strftime("%Y-%m-%d"),
})

# ===================================================================
# 2. ОПЕРАЦИИ ПО КАРТАМ
# ===================================================================
# Для каждой категории: (типичная сумма в рублях, доля среди всех операций)
cats = {
    "Супермаркеты": (1100, 0.30), "Рестораны": (1600, 0.12), "Такси": (520, 0.12),
    "Маркетплейсы": (2300, 0.15), "АЗС": (2600, 0.07), "Аптеки": (900, 0.06),
    "Развлечения": (1400, 0.05), "Одежда": (4200, 0.05), "Путешествия": (18000, 0.03),
    "Связь": (650, 0.05),
}
cat_names = list(cats)
cat_w = np.array([cats[c][1] for c in cat_names])
cat_w /= cat_w.sum()  # нормируем доли, чтобы в сумме было ровно 1

# Во сколько раз чек сегмента больше массового, и сколько операций в среднем за период
mult = {"Массовый": 1.0, "Массовый высокодоходный": 1.8, "Премиум": 3.2}
freq = {"Массовый": 14, "Массовый высокодоходный": 22, "Премиум": 28}

# 45 случайных клиентов, у которых не будет ни одной операции
inactive = set(rng.choice(clients.client_id, 45, replace=False))

days = pd.date_range("2026-01-01", "2026-10-31")  # период данных

# Сезонность: множитель по месяцам январь…октябрь.
# Путешествия: пик в июле-августе. Одежда: всплески в марте и сентябре.
season = {
    "Путешествия": [0.5, 0.5, 0.7, 0.8, 1.0, 2.0, 2.6, 2.4, 1.1, 0.7],
    "Одежда":      [0.8, 0.7, 1.4, 1.1, 0.9, 0.8, 0.8, 0.9, 1.5, 1.1],
}

rows = []
for cid, s in zip(clients.client_id, clients.segment):
    if cid in inactive:
        continue
    # число операций клиента — случайное, в среднем freq[s] (распределение Пуассона)
    n = rng.poisson(freq[s])
    if n == 0:
        continue
    d = days[rng.integers(0, len(days), n)]           # случайные дни операций
    c = rng.choice(cat_names, n, p=cat_w)              # случайные категории по долям
    # Сезонность через «прореживание»: операцию по сезонной категории оставляем
    # с вероятностью множитель_месяца / 2.6. В пиковый месяц остаются все,
    # в несезон — меньше половины. Остальные категории остаются всегда.
    keep = np.array([
        rng.random() < season.get(ci, [1] * 10)[di.month - 1] / 2.6 if ci in season else True
        for ci, di in zip(c, d)
    ])
    for di, ci in zip(d[keep], c[keep]):
        med = cats[ci][0] * mult[s]  # типичная сумма для этой категории и сегмента
        # Сумма по логнормальному закону: в основном около med,
        # но иногда бывают крупные чеки — как в реальных тратах.
        amt = round(float(np.exp(rng.normal(np.log(med), 0.6))), 2)
        channel = rng.choice(["Карта", "СБП", "Онлайн"], p=[0.7, 0.2, 0.1])
        rows.append((cid, di.strftime("%Y-%m-%d"), ci, amt, channel))

tx = (pd.DataFrame(rows, columns=["client_id", "txn_date", "category", "amount", "channel"])
        .sort_values(["txn_date", "client_id"])
        .reset_index(drop=True))
tx.insert(0, "txn_id", np.arange(1, len(tx) + 1))  # номер операции 1, 2, 3...

# ===================================================================
# 3. ПОКАЗЫ ПРЕДЛОЖЕНИЙ (то, что рекомендует система клиенту)
# ===================================================================
# Предложение -> категория трат, к которой оно относится (None = ни к какой)
offers_def = {
    "Кешбэк в ресторанах": "Рестораны", "Кешбэк на такси": "Такси",
    "Кешбэк на маркетплейсах": "Маркетплейсы", "Кредитная карта": None,
    "Вклад": None, "Страхование путешествий": "Путешествия",
}
# Для каждого клиента — набор категорий, в которых он реально тратил
spend_cats = tx.groupby("client_id")["category"].agg(set).to_dict()

orows = []
for cid, s, pr in zip(clients.client_id, clients.segment, clients.has_sberprime):
    for _ in range(rng.integers(2, 7)):           # каждому клиенту 2–6 показов
        o = rng.choice(list(offers_def))
        shown = days[rng.integers(0, len(days))]
        # Базовая вероятность клика
        base = {"Кредитная карта": 0.05, "Вклад": 0.08}.get(o, 0.06)
        # Релевантное предложение (клиент и так тратит в этой категории) кликают в 2,6 раза чаще
        if offers_def[o] and offers_def[o] in spend_cats.get(cid, set()):
            base *= 2.6
        # Вклад интереснее клиентам с высоким доходом
        if o == "Вклад" and s != "Массовый":
            base *= 2.0
        # Подписчики СберПрайма активнее
        if pr:
            base *= 1.3
        clicked = int(rng.random() < base)
        converted = int(clicked and rng.random() < 0.35)  # 35% кликнувших оформляют
        orows.append((cid, shown.strftime("%Y-%m-%d"), o, clicked, converted))

offers = (pd.DataFrame(orows, columns=["client_id", "shown_date", "offer", "clicked", "converted"])
            .sort_values("shown_date")
            .reset_index(drop=True))
offers.insert(0, "show_id", np.arange(1, len(offers) + 1))

# ===================================================================
# 4. СОХРАНЕНИЕ В SQLite
# ===================================================================
# sqlite3.connect создаёт файл базы, если его ещё нет.
# DataFrame.to_sql сам создаёт таблицу и записывает в неё строки.
DB = Path(__file__).resolve().parent / "b2c.db"
con = sqlite3.connect(DB)
for name, df in [("clients", clients), ("transactions", tx), ("offers", offers)]:
    df.to_sql(name, con, if_exists="replace", index=False)  # replace = перезаписать таблицу
con.commit()
con.close()

print(f"Готово: {len(clients)} клиентов, {len(tx)} операций, {len(offers)} показов -> b2c.db")
